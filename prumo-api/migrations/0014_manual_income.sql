CREATE TABLE finance.events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  household_id uuid NOT NULL REFERENCES household.households(id),
  type text NOT NULL CHECK (type = 'RECEIVED_INCOME'),
  current_version integer NOT NULL DEFAULT 1 CHECK (current_version = 1),
  UNIQUE (household_id, id)
);
CREATE TABLE finance.event_versions (
  household_id uuid NOT NULL,
  event_id uuid NOT NULL,
  version integer NOT NULL CHECK (version = 1),
  movement_id uuid NOT NULL,
  account_id uuid NOT NULL,
  amount_cents bigint NOT NULL CHECK (amount_cents BETWEEN 1 AND 9007199254740991),
  currency text NOT NULL CHECK (currency = 'BRL'),
  effective_date date NOT NULL,
  description text NOT NULL CHECK (length(description) BETWEEN 1 AND 240 AND description = btrim(description)),
  state text NOT NULL CHECK (state IN ('APPLIED', 'PENDING_PRE_OPENING')),
  date_provenance text NOT NULL CHECK (date_provenance = 'MANUAL_USER'),
  recorded_by_user_id uuid NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (household_id, event_id, version),
  UNIQUE (household_id, event_id, version, movement_id, account_id, amount_cents, effective_date, state),
  FOREIGN KEY (household_id, event_id) REFERENCES finance.events(household_id, id),
  FOREIGN KEY (household_id, account_id) REFERENCES finance.accounts(household_id, id),
  FOREIGN KEY (household_id, recorded_by_user_id) REFERENCES household.memberships(household_id, user_id)
);
CREATE TABLE finance.movements (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  household_id uuid NOT NULL,
  event_id uuid NOT NULL,
  version integer NOT NULL CHECK (version = 1),
  account_id uuid NOT NULL,
  amount_cents bigint NOT NULL CHECK (amount_cents BETWEEN 1 AND 9007199254740991),
  effective_date date NOT NULL,
  state text NOT NULL CHECK (state IN ('APPLIED', 'PENDING_PRE_OPENING')),
  sequence bigint GENERATED BY DEFAULT AS IDENTITY,
  PRIMARY KEY (household_id, id, version),
  UNIQUE (household_id, event_id, version),
  FOREIGN KEY (household_id, event_id, version, id, account_id, amount_cents, effective_date, state)
    REFERENCES finance.event_versions(household_id, event_id, version, movement_id, account_id, amount_cents, effective_date, state)
    DEFERRABLE INITIALLY DEFERRED
);
ALTER TABLE finance.event_versions ADD CONSTRAINT version_requires_movement
  FOREIGN KEY (household_id, movement_id, version) REFERENCES finance.movements(household_id, id, version)
  DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE finance.events ADD CONSTRAINT event_requires_current_version
  FOREIGN KEY (household_id, id, current_version) REFERENCES finance.event_versions(household_id, event_id, version)
  DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX movements_account_page_idx ON finance.movements(household_id, account_id, effective_date, sequence);
CREATE TABLE finance.income_requests (
  household_id uuid NOT NULL REFERENCES household.households(id),
  operation text NOT NULL CHECK (operation = 'income:create'),
  request_key uuid NOT NULL,
  actor_user_id uuid NOT NULL,
  request_payload jsonb NOT NULL,
  event_id uuid NOT NULL,
  response jsonb NOT NULL,
  PRIMARY KEY (household_id, operation, request_key),
  FOREIGN KEY (household_id, actor_user_id) REFERENCES household.memberships(household_id, user_id),
  FOREIGN KEY (household_id, event_id) REFERENCES finance.events(household_id, id)
);
